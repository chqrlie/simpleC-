out = []
out.append("// nano-font.h — an 8x8 bitmap console font, ASCII 32..126.")
out.append("//")
out.append("// Designed for this project rather than lifted from an existing font file,")
out.append("// so there is no licence to carry around. One byte per row, low bit = leftmost")
out.append("// pixel, eight rows per glyph; rows 0..6 hold the glyph and row 7 is the")
out.append("// descender line, used by g j p q y and the underscore.")
out.append("//")
out.append("// Generated by tools/genfont.py — edit that, not this.")
out.append("")
out.append("#ifndef NANO_FONT_H")
out.append("#define NANO_FONT_H")
out.append("")
out.append("#define FONT_FIRST 32")
out.append("#define FONT_LAST  126")
out.append("#define FONT_W     8")
out.append("#define FONT_H     8")
out.append("")
out.append("char g_font[(FONT_LAST - FONT_FIRST + 1) * FONT_H] = {")
for c in range(32, 127):
    ch = chr(c)
    rows = G.get(ch)
    if rows is None:
        raise SystemExit("missing glyph for %r (%d)" % (ch, c))
    vals = []
    for r in rows:
        v = 0
        for i, p in enumerate(r):
            if p == '#':
                v |= (1 << i)          # low bit = leftmost pixel
        vals.append(v)
    label = ch if ch not in ('\\',) else '\\\\'
    out.append("    %s   // '%s'" % (", ".join("%3d" % v for v in vals) + ",", label))
out.append("};")
out.append("")
out.append("#endif")
